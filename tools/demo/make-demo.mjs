// Rebuilds the demo city: opens the built game in a headless browser, runs build-demo-city.js
// (which places everything with the game's own rules), lets the city run a few days, prints a
// health report and writes src/js/01b_demo.js, the save the title screen and the Demo slot load.
//
// Needs Playwright once:   npm install --no-save playwright && npx playwright install chromium
// Then run:                npm run demo
// (To use a Chrome you already have, set CHROME_PATH to its executable.)
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(pathToFileURL(path.join(root, 'dist/index.html')).href);
await page.waitForFunction('window.__PA_READY', null, { timeout: 30000 });
const build = JSON.parse(await page.evaluate(fs.readFileSync(path.join(root, 'tools/demo/build-demo-city.js'), 'utf8')));
if (build.fails.length) { console.log('FAILS', JSON.stringify(build.fails)); }
console.log('built pop', build.pop, 'happy', build.happy);

const report = await page.evaluate(() => {
  const P = __PA, G = P.G;
  document.getElementById('title').hidden = true;
  // a summer week: run three days so shops restock, tourists arrive and the books fill in
  G.t = 211 * 1440 + 5 * 60; G.speed = 3; G.money = 2000000; G.loan = 0;
  G.level = 6; G.movingList = 400; G.weather = 'sunny'; G.forecast = 'sunny';
  G.f1.nextRace = 230;
  const days = [];
  let guard = 0;
  while (G.t < 214 * 1440 + 9 * 60 + 30 && guard++ < 5000) { P.advance(0.5); if (G.weather !== 'sunny') { G.weather = 'sunny'; G.forecast = 'sunny'; } }
  for (const h of G.history) days.push({ day: h.day, inc: Math.round(h.income), exp: Math.round(h.expenses), pop: h.pop, happy: h.happy });
  const shops = [...G.buildings.values()].filter((b) => b.goods || P.B[b.type].goods).map((b) => [b.type, b.x, b.y, Object.entries(b.sat || {}).map(([g, v]) => g[0] + (Math.round(v * 100))).join(' '), b.closed ? 'CLOSED' : '']);
  const lowSat = shops.filter((s) => /\d/.test(s[3]) && s[3].split(' ').some((x) => +x.slice(1) < 90));
  return { day: G.day(), minute: G.minute(), pop: G.pop, happy: +G.happy.toFixed(3), money: Math.round(G.money), level: G.level, days, complaints: G.complaints.slice(0, 6), tourists: G.tourists, lowSat, closed: shops.filter((s) => s[4]).length, supply: G.supply };
});
console.log(JSON.stringify(report, null, 1));

const save = await page.evaluate(() => {
  const P = __PA, G = P.G, R = P.R;
  // final touches for the showcase: a healthy treasury, a sunny morning, the next race soon
  G.money = 2400000; G.loan = 0; G.debtDays = 0; G.movingList = 260; G.tax = 'normal';
  G.weather = 'sunny'; G.forecast = 'sunny'; G.name = 'Port Azur';
  G.stats = { built: G.buildings.size, races: 11 };
  if (G.f1) { G.f1.races = 11; G.f1.lastRace = G.day() - 11; G.f1.nextRace = G.day() + 9; G.f1.winner = 'Rosso'; }
  G.petition = null; G.pending = null; G.moods = []; G.protest = null; G.strike = false;
  G.goals = Object.fromEntries(P.GOALS.map((g) => [g.id, true]));
  G.view = 0; P.setView(0); R.zoom = 1.5; P.centerOnTile(44, 25);
  const s = P.serialize();
  s.demo = true; s.savedAt = 0;
  return JSON.stringify(s);
});
const out = `// Generated by tools/demo/make-demo.mjs: the fully grown demo city (title screen and the Demo slot).\nconst DEMO_SAVE = ${save};\n`;
fs.writeFileSync(path.join(root, 'src/js/01b_demo.js'), out);
console.log('wrote src/js/01b_demo.js', (out.length / 1024).toFixed(1) + ' KB', errors.length ? 'ERRORS ' + errors.join(' | ') : '');
await browser.close();
